export const STAGES_PER_WORLD = 5

export const ROMAN = ['I', 'II', 'III', 'IV', 'V']

export const STAGE_TITLES = ['Threshold', 'Ascent', 'Gauntlet', 'Vault', 'Relic']

export function stageKey(world, stage) {
  return `${world}-${stage}`
}

/**
 * Difficulty / goal curve for a single stage.
 * world: 1..20, stage: 1..5
 */
export function getStageConfig(world, stage) {
  const index = (world - 1) * STAGES_PER_WORLD + (stage - 1) // 0..99
  const t = index / 99
  const distance = Math.round(260 + world * 20 + stage * 78)
  const startSpeed = 14.2 + world * 0.52 + stage * 0.22
  const maxSpeed = startSpeed + 4.6 + world * 0.12
  const totalStars = STAGE_TITLES.length

  return {
    id: index,
    world,
    stage,
    index,
    key: stageKey(world, stage),
    title: STAGE_TITLES[stage - 1],
    distance,
    coinGoal: Math.round(distance * (0.128 + stage * 0.003)),
    startSpeed,
    maxSpeed,
    ramp: 0.42 + world * 0.012, // metres / second gained per second
    rowGap: Math.max(8.4, 14.2 - world * 0.19 - stage * 0.32),
    density: 0.32 + t * 0.58,
    difficulty: t,
    hearts: 2,
    magnetTime: 8,
    totalStars,
    reward: 40 + world * 12 + stage * 20,
  }
}

export function worldProgress(profile, world) {
  let stars = 0
  for (let s = 1; s <= STAGES_PER_WORLD; s++) {
    stars += profile.stars[stageKey(world, s)] || 0
  }
  return { stars, max: STAGES_PER_WORLD * 3 }
}

export function totalStars(profile) {
  return Object.values(profile.stars).reduce((a, b) => a + (b || 0), 0)
}
